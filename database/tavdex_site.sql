--  MySQL 8 ou mais recente (também funciona no MySQL do WAMP).
--
--  Como instalar (UM só script):
--    · phpMyAdmin: Importar > escolher este ficheiro > Executar
--    · ou na linha de comandos:  mysql -u root < database/tavdex_site.sql
--  Cria a base de dados "tavdex_site" (o nome que está no .env: BD_NOME=tavdex_site).
--  ATENÇÃO: apaga a base de dados tavdex_site se já existir.
--
--  Contas de exemplo (dados inventados, não são pessoas verdadeiras):
--    Administrador: duarte@tavdex.pt  /  Admin#2026
--    Utilizadores:  <nome sem pontos>@mail.pt  /  tavdex123   (ex.: rafa@mail.pt)
--    (tavdex123 já não cumpre as regras novas: entra, mas o site pede para a mudar)
--
--  Organização:
--    PARTE 1 – TABELAS: contas e segurança · filmes e séries · avaliações e listas ·
--              projetos · comunidade · índices e a vista vw_titulos_avaliacao
--    PARTE 2 – DADOS DE EXEMPLO
--  (As sessões do Express ficam na tabela sessoes_express, que a biblioteca
--   express-mysql-session cria sozinha quando o servidor arranca.)
-- =====================================================================

SET NAMES utf8mb4;
SET default_storage_engine = InnoDB;   -- o WAMP usa MyISAM por omissão, que não tem chaves estrangeiras

DROP DATABASE IF EXISTS tavdex_site;
CREATE DATABASE tavdex_site CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE tavdex_site;

-- =====================================================================
--  PARTE 1 – TABELAS
-- =====================================================================

-- ---------------------------------------------------------------------
-- CONTAS E SEGURANÇA
-- ---------------------------------------------------------------------

-- Contas dos utilizadores (a palavra-passe é guardada encriptada com bcrypt)
CREATE TABLE utilizadores (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nome VARCHAR(30) NOT NULL UNIQUE,                -- @nome de utilizador
    nome_exibicao VARCHAR(50) NULL,                  -- nome no perfil (ex.: "Duarte Tavares"); NULL = mostra o @nome
    email VARCHAR(120) NOT NULL UNIQUE,
    email_pendente VARCHAR(120) NULL,                -- novo email à espera de confirmação
    email_verificado BOOLEAN NOT NULL DEFAULT 0,     -- 1 = o email foi confirmado (link ou Google)
    password_hash VARCHAR(255) NULL,                 -- NULL se a conta só entra com o Google
    google_id VARCHAR(50) NULL UNIQUE,               -- identificador da conta Google (OAuth 2.0)
    google_email VARCHAR(120) NULL,                  -- email da conta Google ligada (pode ser outro)
    bio VARCHAR(160) NOT NULL DEFAULT '',
    localizacao VARCHAR(40) NOT NULL DEFAULT '',
    cor SMALLINT NOT NULL DEFAULT 330,               -- cor do avatar (0 a 359)
    tema_banner ENUM('colina','pipocas','claquete','pelicula','marquise') NOT NULL DEFAULT 'colina',   -- cenário do banner
    foto MEDIUMBLOB NULL,                            -- foto de perfil: JPEG 256×256
    foto_versao INT NOT NULL DEFAULT 0,              -- muda com a foto, para o browser não mostrar a antiga (0 = sem foto)
    papel ENUM('utilizador','admin') NOT NULL DEFAULT 'utilizador',
    bloqueado BOOLEAN NOT NULL DEFAULT 0,
    notif_email BOOLEAN NOT NULL DEFAULT 0,          -- receber as notificações também por email
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ultimo_login DATETIME NULL,
    palavra_passe_alterada_em DATETIME NULL,
    palavra_passe_fraca BOOLEAN NULL,                -- a palavra-passe já não cumpre as regras? (visto no login)
    nome_alterado_em DATETIME NULL,                  -- última mudança do @nome (só pode mudar a cada 30 dias)
    mostrar_listas BOOLEAN NOT NULL DEFAULT TRUE,    -- favoritos, a ver e vistos visíveis no perfil
    mostrar_seguidores BOOLEAN NOT NULL DEFAULT TRUE,   -- seguidores / a seguir visíveis no perfil
    banner MEDIUMBLOB NULL,                          -- imagem própria do banner: JPEG 1500×500 (NULL = usa o cenário)
    banner_versao INT NOT NULL DEFAULT 0             -- muda com a imagem do banner (0 = sem imagem)
);

-- Pedidos de recuperação de palavra-passe (o token é guardado em hash SHA-256)
CREATE TABLE recuperacoes (
    id INT AUTO_INCREMENT PRIMARY KEY,
    utilizador_id INT NOT NULL,
    token_hash CHAR(64) NOT NULL,
    expira_em DATETIME NOT NULL,
    usado BOOLEAN NOT NULL DEFAULT 0,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,   -- no máximo 3 pedidos por hora por conta
    ip VARCHAR(45) NULL,                                      -- no máximo 10 pedidos por hora por IP
    INDEX idx_recuperacoes_ip (ip, criado_em),
    FOREIGN KEY (utilizador_id) REFERENCES utilizadores(id) ON DELETE CASCADE
);

-- Links de confirmação do email (registo e mudança de email)
CREATE TABLE verificacao_email (
    id INT AUTO_INCREMENT PRIMARY KEY,
    utilizador_id INT NOT NULL,
    email VARCHAR(120) NOT NULL,                     -- email que este link confirma
    token CHAR(64) NOT NULL UNIQUE,                  -- hash SHA-256 do token enviado (nunca o token verdadeiro)
    ip VARCHAR(45) NULL,
    expira_em DATETIME NOT NULL,
    usado BOOLEAN NOT NULL DEFAULT FALSE,
    data_pedido DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_verificacao (utilizador_id, data_pedido),
    FOREIGN KEY (utilizador_id) REFERENCES utilizadores(id) ON DELETE CASCADE
);

-- Tentativas de login falhadas: com 5 falhas em 15 minutos o login fica bloqueado.
-- Fica na base de dados (e não na sessão) para não se contornar apagando os cookies.
CREATE TABLE tentativas_login (
    id INT AUTO_INCREMENT PRIMARY KEY,
    email VARCHAR(120) NOT NULL,
    ip VARCHAR(45) NOT NULL,                         -- 45 caracteres chegam para IPv6
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_tentativas (email, criado_em),
    INDEX idx_tentativas_ip (ip, criado_em)
);

-- Sessões ativas por dispositivo. A sessão do Express guarda um token
-- aleatório; aqui fica só o hash SHA-256 desse token. Apagar a linha
-- = terminar a sessão nesse dispositivo.
CREATE TABLE sessoes (
    id INT AUTO_INCREMENT PRIMARY KEY,
    utilizador_id INT NOT NULL,
    token_hash CHAR(64) NOT NULL UNIQUE,
    dispositivo VARCHAR(200) NOT NULL DEFAULT '',    -- navegador / sistema (User-Agent)
    ip VARCHAR(45) NOT NULL DEFAULT '',
    via ENUM('palavra_passe','google') NOT NULL DEFAULT 'palavra_passe',   -- como entrou
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ultimo_acesso TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    manter BOOLEAN NOT NULL DEFAULT FALSE,           -- "Manter sessão iniciada" (30 dias)
    expira_em DATETIME NULL,
    FOREIGN KEY (utilizador_id) REFERENCES utilizadores(id) ON DELETE CASCADE
);

-- Registo de eventos de segurança (aparece em Definições > Atividade recente)
CREATE TABLE atividade_conta (
    id INT AUTO_INCREMENT PRIMARY KEY,
    utilizador_id INT NOT NULL,
    tipo VARCHAR(30) NOT NULL,                       -- código para o programa (ex.: login, login_google)
    descricao VARCHAR(255) NOT NULL DEFAULT '',      -- o que se mostra (ex.: "Sessão iniciada com o Google · Windows · Chrome")
    ip VARCHAR(45) NOT NULL DEFAULT '',
    dispositivo VARCHAR(200) NOT NULL DEFAULT '',
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_atividade (utilizador_id, criado_em),
    FOREIGN KEY (utilizador_id) REFERENCES utilizadores(id) ON DELETE CASCADE
);

-- Quem segue quem
CREATE TABLE seguidores (
    seguidor_id INT NOT NULL,
    seguido_id INT NOT NULL,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (seguidor_id, seguido_id),
    FOREIGN KEY (seguidor_id) REFERENCES utilizadores(id) ON DELETE CASCADE,
    FOREIGN KEY (seguido_id) REFERENCES utilizadores(id) ON DELETE CASCADE
);

-- @nomes antigos: o endereço antigo do perfil redireciona e o @nome
-- fica reservado para o dono durante 30 dias
CREATE TABLE nomes_antigos (
    nome VARCHAR(30) NOT NULL PRIMARY KEY,           -- mesmo tamanho que utilizadores.nome
    utilizador_id INT NOT NULL,
    data DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (utilizador_id) REFERENCES utilizadores(id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- FILMES E SÉRIES
-- ---------------------------------------------------------------------

CREATE TABLE generos (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nome VARCHAR(40) NOT NULL UNIQUE
);

-- Géneros favoritos escolhidos nas Definições (até 3)
CREATE TABLE utilizador_generos (
    utilizador_id INT NOT NULL,
    genero_id INT NOT NULL,
    PRIMARY KEY (utilizador_id, genero_id),
    FOREIGN KEY (utilizador_id) REFERENCES utilizadores(id) ON DELETE CASCADE,
    FOREIGN KEY (genero_id) REFERENCES generos(id) ON DELETE CASCADE
);

-- Filmes e séries do catálogo
CREATE TABLE titulos (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    tipo ENUM('filme','serie') NOT NULL,
    ano SMALLINT NOT NULL,
    duracao_min SMALLINT NULL,                       -- só para filmes
    idade VARCHAR(5) NOT NULL DEFAULT 'M/12',        -- classificação etária
    sinopse TEXT NOT NULL,
    realizador VARCHAR(100) NOT NULL DEFAULT '',     -- realizador ou criador
    cartaz VARCHAR(255) NULL,                        -- endereço https da imagem do cartaz
    fundo VARCHAR(255) NULL,                         -- imagem larga para o destaque
    tmdb_id INT NULL,                                -- número do título no TMDB (opcional)
    em_curso BOOLEAN NOT NULL DEFAULT 0,             -- só para séries
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_titulos_nome (nome),
    INDEX idx_titulos_tipo_ano (tipo, ano)
);

-- Um título pode ter vários géneros (relação N:N)
CREATE TABLE titulo_generos (
    titulo_id INT NOT NULL,
    genero_id INT NOT NULL,
    PRIMARY KEY (titulo_id, genero_id),
    FOREIGN KEY (titulo_id) REFERENCES titulos(id) ON DELETE CASCADE,
    FOREIGN KEY (genero_id) REFERENCES generos(id) ON DELETE CASCADE
);

-- Plataformas de streaming (Netflix, Disney+, ...) para a secção "Onde ver"
CREATE TABLE plataformas (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nome VARCHAR(40) NOT NULL UNIQUE,
    cor CHAR(7) NOT NULL DEFAULT '#888888',          -- cor da etiqueta, ex.: #E50914
    url VARCHAR(200) NOT NULL DEFAULT '',            -- página inicial da plataforma
    logo VARCHAR(255) NULL                           -- endereço do logótipo (opcional)
);

-- Onde está disponível cada título (relação N:N), com o link direto (opcional)
CREATE TABLE titulo_plataformas (
    titulo_id INT NOT NULL,
    plataforma_id INT NOT NULL,
    link VARCHAR(255) NOT NULL DEFAULT '',
    PRIMARY KEY (titulo_id, plataforma_id),
    FOREIGN KEY (titulo_id) REFERENCES titulos(id) ON DELETE CASCADE,
    FOREIGN KEY (plataforma_id) REFERENCES plataformas(id) ON DELETE CASCADE
);

-- Pessoas do elenco e da equipa técnica
CREATE TABLE pessoas (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    foto VARCHAR(255) NULL,                          -- endereço de uma imagem (opcional)
    INDEX idx_pessoas_nome (nome)
);

-- Quem participa em cada título e com que função
CREATE TABLE titulo_pessoas (
    titulo_id INT NOT NULL,
    pessoa_id INT NOT NULL,
    funcao ENUM('ator','realizacao','argumento','producao','musica') NOT NULL,
    personagem VARCHAR(100) NOT NULL DEFAULT '',     -- só para atores
    ordem SMALLINT NOT NULL DEFAULT 0,               -- ordem em que aparece
    PRIMARY KEY (titulo_id, pessoa_id, funcao),
    FOREIGN KEY (titulo_id) REFERENCES titulos(id) ON DELETE CASCADE,
    FOREIGN KEY (pessoa_id) REFERENCES pessoas(id) ON DELETE CASCADE
);

-- Temporadas das séries
CREATE TABLE temporadas (
    id INT AUTO_INCREMENT PRIMARY KEY,
    titulo_id INT NOT NULL,
    numero SMALLINT NOT NULL,
    ano SMALLINT NOT NULL,
    episodios SMALLINT NOT NULL,
    UNIQUE (titulo_id, numero),
    FOREIGN KEY (titulo_id) REFERENCES titulos(id) ON DELETE CASCADE
);

-- Episódios de cada temporada
CREATE TABLE episodios (
    id INT AUTO_INCREMENT PRIMARY KEY,
    temporada_id INT NOT NULL,
    numero SMALLINT NOT NULL,
    nome VARCHAR(150) NOT NULL,
    duracao_min SMALLINT NULL,
    data_estreia DATE NULL,
    UNIQUE (temporada_id, numero),
    FOREIGN KEY (temporada_id) REFERENCES temporadas(id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- AVALIAÇÕES E LISTAS
-- ---------------------------------------------------------------------

-- Classificação de 1 a 5 estrelas e review (opcional) de cada utilizador
CREATE TABLE avaliacoes (
    id INT AUTO_INCREMENT PRIMARY KEY,
    utilizador_id INT NOT NULL,
    titulo_id INT NOT NULL,
    nota TINYINT NOT NULL CHECK (nota BETWEEN 1 AND 5),
    review TEXT NULL,
    spoiler BOOLEAN NOT NULL DEFAULT 0,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    editado_em DATETIME NULL,
    UNIQUE (utilizador_id, titulo_id),               -- uma avaliação por título
    INDEX idx_avaliacoes_titulo (titulo_id),
    FOREIGN KEY (utilizador_id) REFERENCES utilizadores(id) ON DELETE CASCADE,
    FOREIGN KEY (titulo_id) REFERENCES titulos(id) ON DELETE CASCADE
);

-- Listas pessoais: favoritos, para ver e vistos
CREATE TABLE listas (
    utilizador_id INT NOT NULL,
    titulo_id INT NOT NULL,
    tipo ENUM('favorito','ver','visto') NOT NULL,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (utilizador_id, titulo_id, tipo),
    FOREIGN KEY (utilizador_id) REFERENCES utilizadores(id) ON DELETE CASCADE,
    FOREIGN KEY (titulo_id) REFERENCES titulos(id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- PROJETOS CINEMATOGRÁFICOS
-- ---------------------------------------------------------------------

CREATE TABLE projetos (
    id INT AUTO_INCREMENT PRIMARY KEY,
    dono_id INT NOT NULL,
    titulo VARCHAR(100) NOT NULL,
    sinopse TEXT NOT NULL,
    tipo ENUM('Filme','Série','Curta-metragem','Documentário','Videoclipe') NOT NULL,
    genero VARCHAR(60) NOT NULL DEFAULT '',
    estado ENUM('Ideia','Recrutamento','Pré-produção','Em produção','Concluído') NOT NULL DEFAULT 'Ideia',
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (dono_id) REFERENCES utilizadores(id) ON DELETE CASCADE
);

-- Equipa do projeto (realizador, produtor, argumentista, atores, ...)
-- Pode ser um utilizador do TavDex ou apenas um nome
CREATE TABLE projeto_equipa (
    id INT AUTO_INCREMENT PRIMARY KEY,
    projeto_id INT NOT NULL,
    funcao VARCHAR(60) NOT NULL,
    utilizador_id INT NULL,
    nome VARCHAR(60) NOT NULL DEFAULT '',
    FOREIGN KEY (projeto_id) REFERENCES projetos(id) ON DELETE CASCADE,
    FOREIGN KEY (utilizador_id) REFERENCES utilizadores(id) ON DELETE SET NULL
);

-- Funções que o projeto procura (vagas abertas a candidaturas)
CREATE TABLE projeto_vagas (
    id INT AUTO_INCREMENT PRIMARY KEY,
    projeto_id INT NOT NULL,
    funcao VARCHAR(60) NOT NULL,
    descricao VARCHAR(200) NOT NULL DEFAULT '',
    aberta BOOLEAN NOT NULL DEFAULT 1,
    FOREIGN KEY (projeto_id) REFERENCES projetos(id) ON DELETE CASCADE
);

-- Candidaturas a uma vaga de um projeto
CREATE TABLE candidaturas (
    id INT AUTO_INCREMENT PRIMARY KEY,
    vaga_id INT NOT NULL,
    utilizador_id INT NOT NULL,
    mensagem VARCHAR(500) NOT NULL DEFAULT '',
    estado ENUM('pendente','aceite','rejeitada') NOT NULL DEFAULT 'pendente',
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (vaga_id, utilizador_id),
    FOREIGN KEY (vaga_id) REFERENCES projeto_vagas(id) ON DELETE CASCADE,
    FOREIGN KEY (utilizador_id) REFERENCES utilizadores(id) ON DELETE CASCADE
);

-- Avaliações e reviews dos projetos
CREATE TABLE projeto_avaliacoes (
    id INT AUTO_INCREMENT PRIMARY KEY,
    projeto_id INT NOT NULL,
    utilizador_id INT NOT NULL,
    nota TINYINT NOT NULL CHECK (nota BETWEEN 1 AND 5),
    review VARCHAR(1000) NOT NULL DEFAULT '',
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (projeto_id, utilizador_id),
    FOREIGN KEY (projeto_id) REFERENCES projetos(id) ON DELETE CASCADE,
    FOREIGN KEY (utilizador_id) REFERENCES utilizadores(id) ON DELETE CASCADE
);

-- Quem acompanha cada projeto (recebe notificações das novidades)
CREATE TABLE projeto_seguidores (
    projeto_id INT NOT NULL,
    utilizador_id INT NOT NULL,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (projeto_id, utilizador_id),
    FOREIGN KEY (projeto_id) REFERENCES projetos(id) ON DELETE CASCADE,
    FOREIGN KEY (utilizador_id) REFERENCES utilizadores(id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- COMUNIDADE
-- ---------------------------------------------------------------------

-- Publicações do feed (podem falar de um projeto ou de um filme/série, com aviso de spoilers)
CREATE TABLE publicacoes (
    id INT AUTO_INCREMENT PRIMARY KEY,
    utilizador_id INT NOT NULL,
    texto VARCHAR(1000) NOT NULL,
    projeto_id INT NULL,
    titulo_id INT NULL,
    spoiler BOOLEAN NOT NULL DEFAULT 0,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (utilizador_id) REFERENCES utilizadores(id) ON DELETE CASCADE,
    FOREIGN KEY (projeto_id) REFERENCES projetos(id) ON DELETE CASCADE,
    FOREIGN KEY (titulo_id) REFERENCES titulos(id) ON DELETE SET NULL
);

-- Comentários de uma publicação OU de um projeto; pai_id = comentário a que se responde
CREATE TABLE comentarios (
    id INT AUTO_INCREMENT PRIMARY KEY,
    publicacao_id INT NULL,
    projeto_id INT NULL,
    utilizador_id INT NOT NULL,
    pai_id INT NULL,
    texto VARCHAR(1000) NOT NULL,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (publicacao_id) REFERENCES publicacoes(id) ON DELETE CASCADE,
    FOREIGN KEY (projeto_id) REFERENCES projetos(id) ON DELETE CASCADE,
    FOREIGN KEY (utilizador_id) REFERENCES utilizadores(id) ON DELETE CASCADE,
    FOREIGN KEY (pai_id) REFERENCES comentarios(id) ON DELETE CASCADE
);

-- "Gostos" nas publicações (um por utilizador)
CREATE TABLE gostos (
    utilizador_id INT NOT NULL,
    publicacao_id INT NOT NULL,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (utilizador_id, publicacao_id),
    FOREIGN KEY (utilizador_id) REFERENCES utilizadores(id) ON DELETE CASCADE,
    FOREIGN KEY (publicacao_id) REFERENCES publicacoes(id) ON DELETE CASCADE
);

-- Chat da comunidade: para_id NULL = sala geral; caso contrário, mensagem privada
CREATE TABLE mensagens (
    id INT AUTO_INCREMENT PRIMARY KEY,
    de_id INT NOT NULL,
    para_id INT NULL,
    texto VARCHAR(1000) NOT NULL,
    editada BOOLEAN NOT NULL DEFAULT 0,
    data_edicao DATETIME NULL,                       -- data da última edição
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_mensagens_conversa (de_id, para_id),
    FOREIGN KEY (de_id) REFERENCES utilizadores(id) ON DELETE CASCADE,
    FOREIGN KEY (para_id) REFERENCES utilizadores(id) ON DELETE CASCADE
);

-- Notificações de cada utilizador
CREATE TABLE notificacoes (
    id INT AUTO_INCREMENT PRIMARY KEY,
    utilizador_id INT NOT NULL,
    tipo ENUM('seguidor','comentario','candidatura','mensagem','projeto','sistema','gosto') NOT NULL,
    texto VARCHAR(255) NOT NULL,
    link VARCHAR(200) NOT NULL DEFAULT '',
    lida BOOLEAN NOT NULL DEFAULT 0,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_notificacoes_utilizador (utilizador_id, lida),
    FOREIGN KEY (utilizador_id) REFERENCES utilizadores(id) ON DELETE CASCADE
);

-- Tipos de notificação que cada utilizador silenciou
CREATE TABLE notif_silenciadas (
    utilizador_id INT NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    PRIMARY KEY (utilizador_id, tipo),
    FOREIGN KEY (utilizador_id) REFERENCES utilizadores(id) ON DELETE CASCADE
);

-- Denúncias de conteúdos, analisadas pelos administradores
CREATE TABLE denuncias (
    id INT AUTO_INCREMENT PRIMARY KEY,
    utilizador_id INT NOT NULL,
    tipo ENUM('publicacao','comentario','review','mensagem') NOT NULL,
    alvo_id INT NOT NULL,
    motivo VARCHAR(40) NOT NULL,
    estado ENUM('pendente','resolvida','ignorada') NOT NULL DEFAULT 'pendente',
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (utilizador_id) REFERENCES utilizadores(id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- VISTA: cada título com a média e o número de avaliações.
-- Usada no catálogo, na pesquisa e nas filas da página inicial.
-- ---------------------------------------------------------------------
CREATE VIEW vw_titulos_avaliacao AS
SELECT t.*,
       ROUND(AVG(a.nota), 1) AS media,
       COUNT(a.id) AS total_avaliacoes
FROM titulos t
LEFT JOIN avaliacoes a ON a.titulo_id = t.id
GROUP BY t.id;

